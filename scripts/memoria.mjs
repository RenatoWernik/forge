import { arranca } from '../templates/.claude/start-ai-memory.mjs';

// /forge:new-project, ai-memory step. --plan --dest <project> prints what would be set up and writes nothing; --apply --dest <project> does it:
// a data dir of its own and a free port for this project, the capture hooks and the MCP server in files git ignores, and the server started hidden.
// The token ai-memory keeps in <dataDir>/auth-tokens is never read here, and install-hooks / install-mcp are never run: they embed it.
// Exit codes: 0 done, 1 any error (no binary, a refused path, a file that is not valid JSON), 2 invalid use or another server on the port.
const aim = createRequire(import.meta.url)('../templates/.claude/ai-memory.cjs');
const FORBIDDEN_PORTS = [4790, 49374, 49375]; // the Guild server, and the two servers of the user's own ai-memory
const NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/;
const LOCAL_URL = /^http:\/\/127\.0\.0\.1:([0-9]{1,5})$/;
const BAD_CHAR = new RegExp('["\\p{Cc}\\u2028\\u2029]', 'u'); // a path with these would break the TOML and JSON written from it
const SETTINGS = '.claude/settings.local.json';
const MCP = '.mcp.json';
const TOML = '.ai-memory.local.toml';
const IGNORED = [SETTINGS, MCP, TOML]; // machine files: they hold this machine's paths and port
const EVENTS = [['SessionStart', 'session-start'], ['UserPromptSubmit', 'user-prompt-submit'], ['PreToolUse', 'pre-tool-use'], ['PostToolUse', 'post-tool-use'],
  ['PreCompact', 'pre-compact'], ['Stop', 'stop'], ['SessionEnd', 'session-end'], ['SubagentStart', 'subagent-start'], ['SubagentStop', 'subagent-stop']];
const FORGE_HOOK = { type: 'command', command: 'node', args: ['${CLAUDE_PROJECT_DIR}/.claude/hooks/forge-ai-memory.mjs'], timeout: 10 };
const USAGE = 'Usage: memoria.mjs --plan --dest <project>\n       memoria.mjs --apply --dest <project>';

const fwd = (p) => String(p).replace(/\\/g, '/').replace(/\/+$/, '');
// a value that came from the environment or a file never ends a line or starts a new one
const show = (v) => String(v).replace(new RegExp('[\\p{Cc}\\u2028\\u2029]', 'gu'), (ch) => '\\u' + ch.codePointAt(0).toString(16).padStart(4, '0'));
const isObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

function defaultDataDir({ platform, env, home }, name) {
  const base = platform === 'win32' ? env.LOCALAPPDATA || `${home}/AppData/Local`
    : platform === 'darwin' ? `${home}/Library/Application Support`
      : env.XDG_DATA_HOME || `${home}/.local/share`;
  return `${fwd(base)}/forge/ai-memory/${name}`;
}

// -> the plan, or { error }; reads only
async function makePlan(sys, dest) {
  const cfg = aim.readConfig(dest);
  const { bin, version, tried } = aim.resolveBin({ env: sys.env, home: sys.home, run: sys.run });
  if (!bin) return { error: `ai-memory not found (looked in: ${tried.map(show).join(', ')}). Run the forge machine check (update.mjs --check).` };
  if (!NAME.test(cfg.workspace ?? '') || !NAME.test(cfg.project ?? '')) return { error: 'no workspace and project in .ai-memory.toml: run this inside a project generated by /forge:new-project.' };
  let port;
  let dataDir;
  if (cfg.serverUrl && cfg.dataDir) { // already set up (this machine): keep the port and the data dir
    port = Number(LOCAL_URL.exec(cfg.serverUrl)?.[1]);
    if (!port || FORBIDDEN_PORTS.includes(port)) return { error: `[forge] server_url must be http://127.0.0.1:<port> with a port outside ${FORBIDDEN_PORTS.join(', ')}.` };
    dataDir = fwd(cfg.dataDir);
  } else {
    dataDir = defaultDataDir(sys, `${cfg.workspace}--${cfg.project}`);
    for (let i = 0; i < 20 && !port; i++) {
      const p = Number(await sys.freePort());
      if (Number.isInteger(p) && p > 0 && !FORBIDDEN_PORTS.includes(p)) port = p;
    }
    if (!port) return { error: 'no free port found on 127.0.0.1.' };
  }
  const bad = [['ai-memory binary', bin], ['data dir', dataDir]].find(([, v]) => BAD_CHAR.test(v));
  if (bad) return { error: `refused: the ${bad[0]} path has a double quote or a control character (${show(bad[1])}).` };
  return {
    bin, version, dataDir, port, serverUrl: `http://127.0.0.1:${port}`,
    outside: [`${dataDir}/ : the data directory of this project's ai-memory (ai-memory init, only when config.toml is missing)`, `${dataDir}/config.toml : one line, bind = "127.0.0.1:${port}"`,
      `a hidden ai-memory server on 127.0.0.1:${port}, started now and by .claude/start-ai-memory.mjs`],
    inside: [`${TOML} : the [forge] table (server_url, data_dir)`, `${SETTINGS} : the 9 capture hooks, the SessionStart notice and enabledMcpjsonServers`, `${MCP} : the ai-memory MCP server`, `.gitignore : the three machine files above`],
  };
}

function readJson(fs, file, rel) {
  if (!fs.existsSync(file)) return {};
  let v;
  try { v = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^﻿/, '')); } catch (e) {
    throw new Error(`${rel} is not valid JSON (${String(e.message).split('\n')[0]}). forge wrote nothing: fix the file or move it away, then run again.`);
  }
  const hooksOk = v?.hooks === undefined || (isObject(v.hooks) && Object.values(v.hooks).every(Array.isArray));
  if (!isObject(v) || !hooksOk || (v.enabledMcpjsonServers !== undefined && !Array.isArray(v.enabledMcpjsonServers)) || (v.mcpServers !== undefined && !isObject(v.mcpServers))) {
    throw new Error(`${rel} does not have the shape of a Claude Code file (an object, "hooks" as an object of lists). forge wrote nothing.`);
  }
  return v;
}

// our hooks are told apart from the user's by the data dir in their args (a new port replaces the old entry) and by the forge script
const isOurs = (h, dataDir) => (Array.isArray(h?.args) && h.args.some((a) => fwd(a).toLowerCase() === dataDir.toLowerCase()) && h.args.includes('hook'))
  || (Array.isArray(h?.args) && h.args.some((a) => String(a).endsWith('/hooks/forge-ai-memory.mjs')));

function mergeSettings(s, p) {
  const hooks = { ...s.hooks };
  for (const [event, name] of EVENTS) {
    const kept = (hooks[event] ?? []).flatMap((g) => {
      if (!Array.isArray(g?.hooks)) return [g];
      const rest = g.hooks.filter((h) => !isOurs(h, p.dataDir));
      return rest.length === g.hooks.length ? [g] : rest.length ? [{ ...g, hooks: rest }] : [];
    });
    const ours = { matcher: '', hooks: [{ type: 'command', command: p.bin, args: ['--data-dir', p.dataDir, 'hook', '--event', name, '--agent', 'claude-code', '--server-url', p.serverUrl] }] };
    hooks[event] = [...kept, ours, ...(event === 'SessionStart' ? [{ matcher: '', hooks: [FORGE_HOOK] }] : [])];
  }
  const enabled = s.enabledMcpjsonServers ?? [];
  return { ...s, hooks, enabledMcpjsonServers: enabled.includes('ai-memory') ? enabled : [...enabled, 'ai-memory'] };
}

const mergeMcp = (m, p) => ({ ...m, mcpServers: { ...m.mcpServers, 'ai-memory': { type: 'stdio', command: p.bin, args: ['mcp-bridge', '--server-url', `${p.serverUrl}/mcp`, '--data-dir', p.dataDir] } } });

// the one top-level bind line of the ai-memory config.toml; the rest of the file stays as it is
function withBind(text, port) {
  const bind = `bind = "127.0.0.1:${port}"`;
  let seen = false;
  let inTable = false;
  const lines = text.split('\n').flatMap((l) => {
    inTable ||= /^\s*\[/.test(l);
    if (inTable || !/^\s*bind\s*=/.test(l)) return [l];
    if (seen) return [];
    seen = true;
    return [bind + (l.endsWith('\r') ? '\r' : '')];
  });
  return seen ? lines.join('\n') : `${bind}\n${text}`;
}

// the [forge] table of the local toml: kept as it is when it has both keys, completed when it lacks one, appended when there is none
function withForge(text, p) {
  const nl = text.includes('\r\n') ? '\r\n' : '\n';
  const lines = text === '' ? ["# This machine's ai-memory server for this project (not versioned). Written by forge's memoria.mjs --apply."] : text.split(/\r?\n/);
  const want = [['server_url', p.serverUrl], ['data_dir', p.dataDir]];
  const head = lines.findIndex((l) => /^\s*\[forge\]\s*(#.*)?$/.test(l));
  if (head < 0) {
    while (lines.at(-1) === '') lines.pop();
    return [...lines, '', '[forge]', ...want.map(([k, v]) => `${k} = "${v}"`), ''].join(nl);
  }
  const next = lines.findIndex((l, i) => i > head && /^\s*\[/.test(l));
  const body = lines.slice(head + 1, next < 0 ? lines.length : next);
  const missing = want.filter(([k]) => !body.some((l) => new RegExp(`^\\s*${k}\\s*=`).test(l)));
  if (!missing.length) return text;
  lines.splice(head + 1, 0, ...missing.map(([k, v]) => `${k} = "${v}"`));
  return lines.join(nl);
}

function withIgnored(text) {
  const nl = text.includes('\r\n') ? '\r\n' : '\n';
  const have = text.split(/\r?\n/).map((l) => l.trim());
  const missing = IGNORED.filter((rel) => !have.includes(rel) && !have.includes(`/${rel}`));
  return missing.length ? (text === '' || text.endsWith('\n') ? text : text + nl) + missing.join(nl) + nl : text;
}

async function apply(sys, dest, p, write) {
  const fs = sys.fs;
  const put = (rel, text) => {
    const file = join(dest, rel);
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return;
    fs.mkdirSync(dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  };
  const read = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '');
  const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
  let settings;
  let mcp;
  try { // everything that can refuse is read before the first write
    settings = mergeSettings(readJson(fs, join(dest, SETTINGS), SETTINGS), p);
    mcp = mergeMcp(readJson(fs, join(dest, MCP), MCP), p);
  } catch (e) { write(e.message); return 1; }

  const config = join(p.dataDir, 'config.toml');
  if (!fs.existsSync(config)) { // never --force: a data dir that exists is not ours to initialize again
    const r = await sys.run(p.bin, ['init', '--data-dir', p.dataDir], {});
    if (r.code !== 0 || !fs.existsSync(config)) { write(`ai-memory init failed (exit ${r.code}); nothing else was written.`); return 1; }
  }
  const cfgText = fs.readFileSync(config, 'utf8');
  const bound = withBind(cfgText, p.port);
  if (bound !== cfgText) fs.writeFileSync(config, bound);
  put(TOML, withForge(read(join(dest, TOML)), p));
  put(SETTINGS, json(settings));
  put(MCP, json(mcp));
  put('.gitignore', withIgnored(read(join(dest, '.gitignore'))));
  write(`forge memoria: the ai-memory of this project is set up (data dir ${p.dataDir}, ${p.serverUrl}).`);
  return arranca(dest, sys, write);
}

export async function main(argv, sys, write) {
  let o;
  try { o = parseArgs({ args: argv, options: { plan: { type: 'boolean' }, apply: { type: 'boolean' }, dest: { type: 'string' } } }).values; } catch (e) { o = {}; }
  if (!o.dest || Boolean(o.plan) === Boolean(o.apply)) { write(USAGE); return 2; }
  const dest = resolve(o.dest);
  const p = await makePlan(sys, dest);
  if (p.error) { write(p.error); return 1; }
  if (o.plan) { write(JSON.stringify(p, null, 2)); return 0; }
  return apply(sys, dest, p, write);
}

const freePort = () => new Promise((res, rej) => {
  const s = createServer();
  s.once('error', rej);
  s.listen(0, '127.0.0.1', () => { const { port } = s.address(); s.close(() => res(port)); });
});

const realSys = { platform: process.platform, env: process.env, home: homedir(), fs: nodeFs, run: aim.run, spawn, fetch: globalThis.fetch, freePort };

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main(process.argv.slice(2), realSys, console.log);
}
