// learnings/ passa a ter só o README armadilha e os ficheiros dados ({ 'AAAA-MM.md': texto | Buffer }); null apaga a pasta
export const registo = (proj, ficheiros, { readme = true } = {}) => {
  apaga(join(proj, 'learnings'));
  if (ficheiros === null) return;
  mkdirSync(join(proj, 'learnings'), { recursive: true });
  if (readme) writeFileSync(join(proj, 'learnings', 'README.md'), README);
  for (const [n, t] of Object.entries(ficheiros)) writeFileSync(join(proj, 'learnings', n), t);
};

const lfs = (s) => s.replace(/\r\n/g, '\n');
const resultado = (r) => {
  const stdout = r.stdout || '', stderr = r.stderr || '';
  const t = lfs(stdout).replace(/\n+$/, '');
  return { status: r.status, stdout, stderr, out: stdout + stderr, linhas: t ? t.split('\n') : [] };
};
const existeLearn = (proj) => assert.ok(existsSync(join(proj, LEARN)), `o projeto gerado não tem ${LEARN}: o F-22b não está implementado (o scaffold tem de o copiar)`);

// Corre `node .claude/learn.mjs <args>` na raiz do projeto, com o ambiente do sandbox
export const learn = (proj, args) => {
  existeLearn(proj);
  return resultado(spawnSync(process.execPath, [LEARN, ...args], { cwd: proj, encoding: 'utf8', env: ambiente(), timeout: 120000 }));
};
// O mesmo, assíncrono (para a corrida de 8 processos em paralelo)
export const learnAsync = (proj, args) => new Promise((done) => {
  existeLearn(proj);
  const c = spawn(process.execPath, [LEARN, ...args], { cwd: proj, env: ambiente() });
  let stdout = '', stderr = '';
  c.stdout.on('data', (d) => { stdout += d; });
  c.stderr.on('data', (d) => { stderr += d; });
  const timer = setTimeout(() => c.kill(), 120000);
  c.on('close', (status) => { clearTimeout(timer); done(resultado({ status, stdout, stderr })); });
});

