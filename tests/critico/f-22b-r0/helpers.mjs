// O bloco gerado de um texto: as linhas entre os marcadores (sem eles), o texto antes do marcador de início e o depois do de fim; null sem bloco
export const blocoDe = (texto) => {
  const t = lfs(texto), i = t.indexOf('\n' + INI + '\n'), j = i < 0 ? -1 : t.indexOf('\n' + FIM, i + INI.length + 1);
  if (i < 0 || j < 0) return null;
  return { antes: t.slice(0, i + 1), linhas: t.slice(i + INI.length + 2, j).split('\n'), depois: t.slice(j + 1 + FIM.length) };
};
// O bloco de CLAUDE.md e de AGENTS.md: existe, está debaixo de `## Learned rules`, tem as linhas esperadas e é igual nos dois
export const esperaBloco = (proj, esperado) => {
  for (const f of ['CLAUDE.md', 'AGENTS.md']) {
    const b = blocoDe(ler(proj, f));
    assert.ok(b, `${f} não tem o bloco ${INI} … ${FIM}`);
    assert.equal(b.antes.replace(/\s+$/, '').split('\n').pop(), SECAO, `${f}: o bloco não está debaixo do cabeçalho «${SECAO}»`);
    assert.deepEqual(b.linhas, esperado, `${f}: o conteúdo entre os marcadores não é o da golden`);
  }
};

